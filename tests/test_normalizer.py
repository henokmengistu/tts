def test_cardinal(n, words):
    assert cardinal(n) == words


@pytest.mark.parametrize("n,words", [
    (1, "አንደኛ"), (2, "ሁለተኛ"), (3, "ሶስተኛ"), (9, "ዘጠነኛ"), (10, "አስረኛ"), (11, "አስራ አንደኛ"),
    (20, "ሃያኛ"), (21, "ሃያ አንደኛ"), (100, "መቶኛ"), (1000, "አንድ ሺኛ"),
])
def test_ordinal(n, words):
    assert ordinal(n) == words


def test_decimal_and_digits():
    assert decimal("3", "14") == "ሶስት ነጥብ አንድ አራት"
    assert decimal("0", "5") == "ዜሮ ነጥብ አምስት"
    assert digits("0911") == "ዜሮ ዘጠኝ አንድ አንድ"


@pytest.mark.parametrize("s,n", [("፩", 1), ("፲", 10), ("፲፭", 15), ("፻", 100), ("፪፻", 200), ("፳፻፲፱", 2019),
                                 ("፼", 10000), ("፲፻", 1000), ("፱፼፱፻፲፱", 90919)])
def test_ethiopic_numerals(s, n):
    assert ethiopic_to_int(s) == n



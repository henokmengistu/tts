def test_homophone_merging():
    n = AmharicNormalizer(merge_homophones=True)
    assert n.normalize("ሐመር ሠላም ፀሐይ ዐይን") == "ሀመር ሰላም ጸሀይ አይን"
    # labialised ኋ must survive
    assert n.normalize("በኋላ") == "በኋላ"


def test_idempotent_and_empty():
    assert normalize("") == ""
    assert normalize("   ") == ""
    once = normalize("ዶ/ር አበበ 25% አለ።")
    assert normalize(once) == once


def test_segmentation():
    text = "አንድ ሁለት ሶስት. አራት አምስት! ስድስት? ሰባት\nስምንት"
    assert split_sentences(text) == ["አንድ ሁለት ሶስት.", "አራት አምስት!", "ስድስት?", "ሰባት", "ስምንት"]
    chunks = chunk_text(text, max_chars=20)
    assert "".join(chunks).replace(" ", "") == text.replace(" ", "").replace("\n", "")
    assert all(len(c) <= 24 for c in chunks)
